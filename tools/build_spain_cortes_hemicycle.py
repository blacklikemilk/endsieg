"""Build the Cortes hemicycle: GUI dots, their dynamic images, and the seat calculation.

A parliament is read at a glance, so the chamber is drawn as a semicircle of dots rather
than a list of numbers. 36 dots carry 400 seats between them, each dot coloured by the bloc
that holds it, sweeping left to right in the political order of the chamber.

This script is the single source for four generated artefacts, so changing the number of
dots or the parties only means editing this file:

  interface/endsieg_spain_cortes.gui                       - window, hemicycle, legend
  common/scripted_guis/spain_cortes_scripted_gui.txt       - one image property per dot
  common/scripted_localisation/spain_cortes_dots.txt        - per-dot texture selector
  common/scripted_effects/spain_cortes_hemicycle.txt        - which bloc owns each dot

Run from the mod root:  python tools/build_spain_cortes_hemicycle.py
"""

from __future__ import annotations

import io
import math
import os
import sys

DOTS = 54
SEATS = 400
DOT_PX = 14

WINDOW_W, WINDOW_H = 500, 470
CX, CY_BOTTOM = 250, 214       # centre of the semicircle, on the diameter
# Rings span a full semicircle and are dense enough to read as a chamber rather than a fan:
# each ring holds about one dot per 24px of its own arc.
ROWS = [                    # (radius, count) from the innermost ring outward
    (62, 9),
    (86, 12),
    (108, 15),
    (130, 18),
]

# left to right, as they sit in the chamber
PARTIES = [
    ("socialists", "SPAIN_CORTES_BLOC_SOCIALISTS"),
    ("republicans", "SPAIN_CORTES_BLOC_REPUBLICANS"),
    ("liberals", "SPAIN_CORTES_BLOC_LIBERALS"),
    ("conservatives", "SPAIN_CORTES_BLOC_CONSERVATIVES"),
    ("monarchists", "SPAIN_CORTES_BLOC_MONARCHISTS"),
    ("carlists", "SPAIN_CORTES_BLOC_CARLISTS"),
    ("falange", "SPAIN_CORTES_BLOC_FALANGE"),
]


def dot_positions() -> list[tuple[int, int]]:
    """Every dot on its arc, sorted left to right then by ring, so colour bands are vertical.

    Each ring keeps a constant spacing along its arc, so the inner rows span a narrower angle
    than the outer ones. Spanning a full 180 degrees on every ring is what makes a hemicycle
    read as a fan.
    """
    pts: list[tuple[float, float]] = []
    for radius, count in ROWS:
        for i in range(count):
            # 180 degrees, open at the bottom, so every ring ends on the diameter
            theta = math.pi - (math.pi * i / (count - 1) if count > 1 else math.pi / 2)
            x = CX + radius * math.cos(theta)
            y = CY_BOTTOM - radius * math.sin(theta)
            pts.append((x, y))
    pts.sort(key=lambda p: (round(p[0], 1), p[1]))
    return [(int(round(x)), int(round(y))) for x, y in pts]


def midpoints(n: int) -> list[int]:
    return [int(round((i + 0.5) * SEATS / n)) for i in range(n)]


