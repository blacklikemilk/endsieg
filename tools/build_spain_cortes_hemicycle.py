def emit_scripted_gui() -> str:
    out = ['scripted_gui = {', '',
           '\t# The chamber panel. One image property per dot, so the hemicycle redraws whenever',
           '\t# spain_cortes_recount rewrites the seat map. Generated by',
           '\t# tools/build_spain_cortes_hemicycle.py.',
           '\tspain_cortes_panel = {',
           '\t\tcontext_type = decision_category',
           '\t\twindow_name = "spain_cortes_window"',
           '\t\tvisible = { has_variable = spain_cortes_total }',
           '\t\tai_enabled = { always = no }',
           '',
           '\t\t# The two majority lines sit on the same spot; these make exactly one visible.',
           '\t\ttriggers = {',
           '\t\t\tspain_cortes_left_majority_visible = { check_variable = { var = spain_government_majority value = 1 } }',
           '\t\t\tspain_cortes_no_majority_visible = { check_variable = { var = spain_government_majority value = 0 } }',
           '\t\t}',
           '',
           '\t\tproperties = {']
    for i in range(1, DOTS + 1):
        out.append('\t\t\tspain_cortes_dot_%d = { image = "[spain_cortes_dot_%d_img]" }' % (i, i))
    out += ['\t\t}', '\t}', '}', '']
    return '\n'.join(out)


def emit_loc() -> str:
    out = ['# Overview: scripted localisation for the Cortes hemicycle.',
           '# Each dot resolves its own texture from the bloc that holds it, so the chamber repaints',
           '# when spain_cortes_refresh_display rewrites the seat map.',
           '# Generated by tools/build_spain_cortes_hemicycle.py. Lives under',
           '# common/scripted_localisation/ because the engine only reads defined_text there.',
           '']
    for i in range(1, DOTS + 1):
        out.append(' defined_text = {')
        out.append('  name = spain_cortes_dot_%d_img' % i)
        for n, (party, _label) in enumerate(PARTIES, start=1):
            out.append('  text = {')
            out.append('   trigger = { check_variable = { var = spain_cortes_dot_%d value = %d } }' % (i, n))
            out.append('   localization_key = "GFX_spain_cortes_dot_%s"' % party)
            out.append('  }')
        out.append('  text = { localization_key = "GFX_spain_cortes_dot_empty" }')
        out.append(' }')
    out.append('')
    return '\n'.join(out)


def emit_effect() -> str:
    mids = midpoints(DOTS)
    out = ['# Overview: the seat map behind the Cortes hemicycle.',
           '# One dot per 11 seats. spain_cortes_recount writes the cumulative bloc totals, then this',
           '# decides which bloc owns each dot, so the chamber redraws when the numbers move.',
           '# Generated by tools/build_spain_cortes_hemicycle.py.',
           'spain_cortes_draw_hemicycle = {']
    for i, mid in enumerate(mids, start=1):
        out.append('\tset_variable = { var = spain_cortes_dot_%d value = 8 }' % i)
        out.append('\tif = {')
        out.append('\t\tlimit = { check_variable = { var = spain_cortes_cum_socialists value = %d compare = greater_than_or_equals } }' % mid)
        out.append('\t\tset_variable = { var = spain_cortes_dot_%d value = 1 }' % i)
        out.append('\t}')
        for n, (party, _label) in enumerate(PARTIES[1:], start=2):
            out.append('\telse_if = {')
            out.append('\t\tlimit = { check_variable = { var = spain_cortes_cum_%s value = %d compare = greater_than_or_equals } }' % (party, mid))
            out.append('\t\tset_variable = { var = spain_cortes_dot_%d value = %d }' % (i, n))
            out.append('\t}')
        out.append('')
    out += ['}', '']
    return '\n'.join(out)


def main() -> int:
    positions = dot_positions()
    if len(positions) != DOTS:
        print('expected %d dots, computed %d' % (DOTS, len(positions)))
        return 1

    files = {
        'interface/endsieg_spain_cortes.gui': emit_gui(positions),
        'common/scripted_guis/spain_cortes_scripted_gui.txt': emit_scripted_gui(),
        'common/scripted_localisation/spain_cortes_dots.txt': emit_loc(),
        'common/scripted_effects/spain_cortes_hemicycle.txt': emit_effect(),
    }
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        # localisation needs a UTF-8 BOM; script files must not have one
        encoding = 'utf-8-sig' if path.endswith('.yml') else 'utf-8'
        io.open(path, 'w', encoding=encoding, newline='').write(text)
        print('wrote %-58s %5d lines' % (path, text.count('\n')))
    return 0


if __name__ == '__main__':
    sys.exit(main())
